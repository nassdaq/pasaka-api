// Turns src/data/swahili_bible.json into a compile-time index.
//
// Every verse text goes into one string, and three small tables say where
// each book's chapters, each chapter's verses and each verse's bytes start.
// src/scripture.rs includes the result, so looking anything up is index
// arithmetic on static data: nothing is read or parsed while running. That is
// what lets the crate run as a Barua Function (a fresh WebAssembly instance per
// call, no filesystem) and lets the Docker image be the binary alone.
use std::fmt::Write as _;
use std::{env, fs, path::Path};

use serde::Deserialize;

const SOURCE: &str = "src/data/swahili_bible.json";

#[derive(Deserialize)]
struct Root {
    #[serde(rename = "BIBLEBOOK")]
    books: Vec<Book>,
}

#[derive(Deserialize)]
struct Book {
    book_number: String,
    book_name: String,
    #[serde(rename = "CHAPTER")]
    chapters: Vec<Chapter>,
}

#[derive(Deserialize)]
struct Chapter {
    chapter_number: String,
    #[serde(rename = "VERSES")]
    verses: Vec<Verse>,
}

#[derive(Deserialize)]
struct Verse {
    verse_number: String,
    verse_text: String,
}

fn main() {
    println!("cargo:rerun-if-changed={SOURCE}");
    println!("cargo:rerun-if-changed=build.rs");

    let json = fs::read_to_string(SOURCE).unwrap_or_else(|e| panic!("{SOURCE}: {e}"));
    let root: Root = serde_json::from_str(&json).unwrap_or_else(|e| panic!("{SOURCE}: {e}"));

    let mut text = String::new();
    let mut book_numbers: Vec<u16> = Vec::new();
    let mut book_names: Vec<String> = Vec::new();
    let mut book_chapter_start: Vec<u32> = vec![0];
    let mut chapter_numbers: Vec<u16> = Vec::new();
    let mut chapter_verse_start: Vec<u32> = vec![0];
    let mut verse_numbers: Vec<u16> = Vec::new();
    let mut verse_text_start: Vec<u32> = vec![0];

    for book in &root.books {
        book_numbers.push(number(&book.book_number));
        book_names.push(format!("{:?}", book.book_name)); // a Rust string literal
        for chapter in &book.chapters {
            chapter_numbers.push(number(&chapter.chapter_number));
            for verse in &chapter.verses {
                verse_numbers.push(number(&verse.verse_number));
                text.push_str(&verse.verse_text);
                verse_text_start.push(len(text.len()));
            }
            chapter_verse_start.push(len(verse_numbers.len()));
        }
        book_chapter_start.push(len(chapter_numbers.len()));
    }

    let out_dir = env::var("OUT_DIR").expect("OUT_DIR is set by cargo");
    let out = Path::new(&out_dir);
    fs::write(out.join("verses.txt"), &text).expect("write verses.txt");

    let mut rs = String::from("// Generated by build.rs from src/data/swahili_bible.json. Do not edit.\n");
    rs.push_str("pub static TEXT: &str = include_str!(concat!(env!(\"OUT_DIR\"), \"/verses.txt\"));\n");
    table(&mut rs, "BOOK_NUMBERS", "u16", &book_numbers);
    table(&mut rs, "BOOK_NAMES", "&str", &book_names);
    table(&mut rs, "BOOK_CHAPTER_START", "u32", &book_chapter_start);
    table(&mut rs, "CHAPTER_NUMBERS", "u16", &chapter_numbers);
    table(&mut rs, "CHAPTER_VERSE_START", "u32", &chapter_verse_start);
    table(&mut rs, "VERSE_NUMBERS", "u16", &verse_numbers);
    table(&mut rs, "VERSE_TEXT_START", "u32", &verse_text_start);
    fs::write(out.join("bible_index.rs"), rs).expect("write bible_index.rs");
}

fn number(s: &str) -> u16 {
    s.trim()
        .parse()
        .unwrap_or_else(|_| panic!("{SOURCE}: {s:?} is not a book, chapter or verse number"))
}

fn len(n: usize) -> u32 {
    u32::try_from(n).expect("the Bible fits in u32 offsets")
}

fn table<T: std::fmt::Display>(rs: &mut String, name: &str, ty: &str, items: &[T]) {
    writeln!(rs, "pub static {name}: [{ty}; {}] = [", items.len()).unwrap();
    for row in items.chunks(24) {
        rs.push_str("   ");
        for item in row {
            write!(rs, " {item},").unwrap();
        }
        rs.push('\n');
    }
    rs.push_str("];\n");
}
